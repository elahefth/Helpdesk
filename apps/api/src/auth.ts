import { betterAuth } from "better-auth";
import { eq } from "drizzle-orm";
import { APIError } from "better-auth/api";
import { drizzleAdapter } from "better-auth/adapters/drizzle";
import { USER_ROLES } from "@helpdesk/shared";
import { env, isProduction } from "./env.ts";
import type { Database } from "./db/client.ts";
import * as schema from "./db/schema.ts";

/**
 * A factory rather than a module-level singleton: `getDb()` is deliberately
 * lazy and may return undefined (see db/client.ts), and Better Auth needs a
 * concrete database. Taking the handle as an argument keeps the "API boots
 * without Postgres" contract intact.
 *
 * No secondaryStorage and no session.cookieCache — that is what puts sessions
 * in the `session` table rather than in the cookie, which is the whole point:
 * an admin revokes an agent by deleting a row.
 */
export function createAuth(db: Database) {
  return betterAuth({
    appName: "Helpdesk",
    basePath: "/api/auth",
    baseURL: env.BETTER_AUTH_URL,
    secret: env.BETTER_AUTH_SECRET,
    trustedOrigins: [env.WEB_ORIGIN],
    database: drizzleAdapter(db, { provider: "pg", schema }),
    emailAndPassword: { enabled: true },
    databaseHooks: {
      user: {
        create: {
          // Staff-only console (project-scope.md): students never log in and
          // agents are created by an admin, so POST /sign-up/email must not
          // mint accounts for anyone who can reach the API.
          //
          // The `disableSignUp` option is not used here because it also blocks
          // server-side auth.api.signUpEmail(), leaving no way to create the
          // first user at all. `ctx` is null (and carries no `request`) when
          // Better Auth is called directly in-process, so this closes the HTTP
          // endpoint while leaving a seeding path open. Better Auth documents
          // this hook as the way to gate sign-up conditionally.
          before: async (_user, ctx) => {
            if (ctx?.request) {
              throw new APIError("BAD_REQUEST", {
                message: "Sign up is disabled",
                code: "SIGN_UP_DISABLED",
              });
            }
          },
        },
      },
      session: {
        create: {
          /**
           * Soft deletion's actual enforcement point.
           *
           * `deletedAt` only hides a row from the user list; on its own it does
           * nothing to stop the account signing straight back in. Every sign-in
           * ends in a session insert whatever route it took, so refusing the
           * insert is the one check that cannot be walked around — as opposed to
           * guarding `/sign-in/email`, which would leave any future credential
           * or social route open by default.
           *
           * Queried through the `db` handle this factory already closed over
           * rather than through `ctx`, which is null for in-process calls.
           *
           * The message is Better Auth's own INVALID_EMAIL_OR_PASSWORD, verbatim
           * and deliberately: a deleted account with the right password must be
           * indistinguishable from a wrong password, or this becomes a way to
           * ask the API which accounts used to exist.
           */
          before: async (session) => {
            const [target] = await db
              .select({ deletedAt: schema.user.deletedAt })
              .from(schema.user)
              .where(eq(schema.user.id, session.userId))
              .limit(1);

            if (target?.deletedAt) {
              throw new APIError("UNAUTHORIZED", {
                message: "Invalid email or password",
              });
            }
          },
        },
      },
    },
    user: {
      additionalFields: {
        // `input: false` so nothing user-supplied can hand out "admin".
        // Values come from @helpdesk/shared so the API and the SPA
        // cannot drift.
        role: {
          type: [...USER_ROLES],
          defaultValue: "agent",
          input: false,
        },
        /**
         * Soft-delete marker: null means live, a timestamp means deleted.
         *
         * Declared here rather than added to db/auth-schema.ts by hand, because
         * that file is generated by `@better-auth/cli generate` and a hand-added
         * column would vanish the next time anyone regenerated it. Declaring it
         * as an additional field is what makes the generator emit it.
         *
         * `input: false` for the same reason `role` is: no HTTP payload should
         * be able to set or clear it. DELETE /api/users/:id writes it.
         */
        deletedAt: {
          type: "date",
          required: false,
          input: false,
        },
      },
    },
    advanced: {
      // userSchema in @helpdesk/shared constrains `id` to a UUID; Better
      // Auth's default id format is not one.
      database: { generateId: "uuid" },
      useSecureCookies: isProduction,
    },
  });
}

export type Auth = ReturnType<typeof createAuth>;
