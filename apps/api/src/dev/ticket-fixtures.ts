import type { TicketCategory, TicketStatus } from "@helpdesk/shared";

/**
 * A hundred support emails for the fictional bootcamp, committed as data rather
 * than generated at run time.
 *
 * Version-controlled on purpose (implementation-plan.md 3.6): a corpus that is
 * regenerated on every run makes "the sort looks wrong" unreproducible, and a
 * screenshot taken today stops matching the database tomorrow.
 *
 * Deliberately spread across every axis the queue can be sorted or filtered by,
 * because a realistic-looking corpus that is uniform in one column makes that
 * column's sort look broken:
 *
 * - **Subjects** start across the alphabet, and several share a first word, so
 *   ordering by subject is visibly different from every other ordering and the
 *   cursor's id tiebreaker is actually exercised.
 * - **Senders** repeat — the same student writes more than once — and a handful
 *   have no display name at all, which is the `coalesce(name, email)` fallback
 *   the sender sort and the Sender cell both depend on.
 * - **Categories** include unclassified, which is most of a real inbox: nothing
 *   classifies, so `null` is the honest majority state and the NULLS-last
 *   ordering needs rows to prove itself on.
 * - **Statuses** skew with age — recent mail is open, old mail is closed —
 *   which is what makes a status filter and a date sort interesting together
 *   rather than independent.
 * - **`daysAgo`** is irregular, with clusters and quiet stretches. Evenly
 *   spaced timestamps make a date sort impossible to tell from a stable one.
 */
export interface TicketFixture {
  /** null for mail that arrived with a bare address and no display name. */
  name: string | null;
  email: string;
  subject: string;
  body: string;
  /** null is unclassified, which nothing in the pipeline can currently change. */
  category: TicketCategory | null;
  status: TicketStatus;
  /** Backdated from the moment the seed runs, so the corpus keeps its shape. */
  daysAgo: number;
}

