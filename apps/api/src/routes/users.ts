/**
 * The cursor is the last row's email, base64url'd.
 *
 * `email` is NOT NULL UNIQUE (the `user_email_unique` constraint), so it is a
 * total order by itself — no tiebreaker column and no tuple comparison — and the
 * constraint's btree index already satisfies the ORDER BY. Ordering by
 * `createdAt` instead would need a composite cursor *and* an index this schema
 * cannot get: `db/auth-schema.ts` is generated by `@better-auth/cli` and must
 * not be hand-edited. It would also drag the `timestamp without time zone`
 * round-trip through the driver into the page boundary, where an offset by the
 * local UTC offset would silently skip or duplicate rows.
 *
 * The base64 is not obfuscation. It keeps the sort key from hardening into a
 * de-facto public API, so moving to a composite cursor later is not a breaking
 * change for clients that stored one.
 */
function encodeCursor(email: string): string {
  return Buffer.from(email, "utf8").toString("base64url");
}

function decodeCursor(cursor: string): string {
  // Buffer.from silently drops invalid base64 rather than throwing, so the shape
  // check below is the actual validation and not a second opinion. Reusing the
  // shared schema's email field keeps a second definition of "email" out of here.
  const decoded = Buffer.from(cursor, "base64url").toString("utf8");
  const parsed = userSchema.shape.email.safeParse(decoded);
  if (!parsed.success) throw HttpError.badRequest("Malformed cursor");
  return parsed.data;
}

/**
 * Better Auth owns the credential half of a staff account: it hashes the password
 * and writes it to `account`, and this repo has no second implementation of that.
 * So creating a user goes through its API rather than a Drizzle insert.
 *
 * Two details here are load-bearing, and both look like omissions:
 *
 * 1. `signUpEmail` is called with a `body` and *nothing else* — no `headers`, no
 *    `request`. `databaseHooks.user.create.before` in auth.ts throws whenever
 *    `ctx.request` exists, which is what closes POST /api/auth/sign-up/email to
 *    the internet. Forwarding this route's `req` would trip that same gate and
 *    turn every create into "Sign up is disabled". The in-process call is the
 *    documented seam, and seed.ts opens the first admin through it the same way.
 *
 * 2. `emailAndPassword.autoSignIn` is left at its default of true. Turning it off
 *    switches Better Auth's duplicate-email response to a *synthetic* user
 *    instead of an error — its account-enumeration defence, and exactly wrong for
 *    an admin console, which would report success and create nothing.
 */
async function createStaffAccount(auth: Auth, body: CreateUserBody) {
  try {
    return await auth.api.signUpEmail({
      body: { name: body.name, email: body.email, password: body.password },
    });
  } catch (error) {
    // Better Auth signals expected failures with APIError. Re-shaping them keeps
    // the reply in this API's error envelope, carrying this request's id, instead
    // of surfacing as an unhandled 500.
    if (!(error instanceof APIError)) throw error;

    const code = typeof error.body?.code === "string" ? error.body.code : "";
    // Both USER_ALREADY_EXISTS and USER_ALREADY_EXISTS_USE_ANOTHER_EMAIL mean the
    // same thing to an admin, and Better Auth has changed which one sign-up
    // raises before. The prefix covers both without pinning the version.
    if (code.startsWith("USER_ALREADY_EXISTS")) {
      throw HttpError.conflict("A user with that email already exists.");
    }

    throw new HttpError(
      error.statusCode,
      "sign_up_failed",
      error.body?.message ?? error.message,
    );
  }
}

/**
 * Sets a staff account's password, mirroring what Better Auth's own admin
 * plugin does in `setUserPassword`: hash with the configured hasher, then write
 * the `credential` account row.
 *
 * Mirrored rather than adopted. Enabling the admin plugin to reach one function
 * would also mount /api/admin/* — set-role, ban, impersonate, list-users — on an
 * API whose entire access story is "sign-up is closed and role is input: false".
 * That is a far larger surface than this route needs.
 *
 * `auth.$context` resolves the same adapter and hasher the HTTP endpoints use,
 * so a password set here verifies against the login form without this repo
 * carrying a second implementation of the hash anywhere.
 */
async function setStaffPassword(auth: Auth, userId: string, password: string) {
  const ctx = await auth.$context;
  const hashed = await ctx.password.hash(password);
  const accounts = await ctx.internalAdapter.findAccounts(userId);

  // Every account this app can create gets a credential row at sign-up, so the
  // else branch covers rows that arrived some other way. Without it
  // `updatePassword` would match nothing and still resolve, reporting success
  // for a password that was never stored.
  if (accounts.some((account) => account.providerId === "credential")) {
    await ctx.internalAdapter.updatePassword(userId, hashed);
  } else {
    await ctx.internalAdapter.createAccount({
      userId,
      providerId: "credential",
      accountId: userId,
      password: hashed,
    });
  }
}

/**
 * Bun's driver puts the SQLSTATE on `errno` — `code` carries Bun's own
 * "ERR_POSTGRES_SERVER_ERROR" and is identical for every server-side failure.
 * 23505 is unique_violation, and matching the constraint name as well stops a
 * unique index added later from reporting itself as a duplicate email.
 *
 * The cause chain is walked because Drizzle does not rethrow the driver's error:
 * it wraps it in a `DrizzleQueryError` carrying the SQL and params, so the
 * fields above are one level down. Reading them off the thrown object alone
 * looks right, passes a driver-level probe, and turns every duplicate email
 * into a 500 in the one place it matters. The depth cap guards a cyclic
 * `cause`, not any shape this has actually been seen to take.
 *
 * Exported only so users.test.ts can pin the wrapping, which no test with a
 * stubbed database can reach and which CI would otherwise never exercise.
 */
export function isDuplicateEmail(error: unknown): boolean {
  let current: unknown = error;

  for (let depth = 0; depth < 5; depth += 1) {
    if (typeof current !== "object" || current === null) return false;

    const { errno, constraint, cause } = current as {
      errno?: unknown;
      constraint?: unknown;
      cause?: unknown;
    };
    if (errno === "23505" && constraint === "user_email_unique") return true;

    current = cause;
  }

  return false;
}

/**
 * A factory taking the database handle, unlike its neighbour `ticketsRouter`,
 * which is a module-level const because it has no dependencies to inject. Per
 * CLAUDE.md, db-dependent modules take the handle — `getDb()` may return
 * undefined, and this route needs to answer for that rather than assume it.
 *
 * `auth` arrives the same way and for the same reason: it only exists when a
 * database does, so POST has to answer for its absence rather than assume it.
 */
export function createUsersRouter(
  db: Database | undefined,
  auth: Auth | undefined,
): Router {
  const router = Router();

  router.get("/users", requireRole("admin"), async (req, res) => {
    // Both forms of input validation run before the database check, so a
    // malformed request gets a 400 that describes it rather than a 503 that
    // blames the database. Throws ZodError on bad input; Express 5 routes that
    // to the error handler as `validation_failed`.
    const query = listUsersQuerySchema.parse(req.query);
    const after = query.cursor ? decodeCursor(query.cursor) : undefined;

    req.log.debug({ query }, "listing users");

    if (!db) throw HttpError.serviceUnavailable("Database unavailable");

    const rows = await db
      .select({
        id: user.id,
        name: user.name,
        email: user.email,
        role: user.role,
        createdAt: user.createdAt,
      })
      .from(user)
      .where(
        and(
          after ? gt(user.email, after) : undefined,
          // A NULL role has to match the "agent" filter, because that is how the
          // projection below renders it. Filtering with a bare equality would
          // make such a row visible in the unfiltered list and invisible when
          // narrowed to agents.
          query.role === "agent"
            ? or(eq(user.role, "agent"), isNull(user.role))
            : query.role
              ? eq(user.role, query.role)
              : undefined,
        ),
      )
      .orderBy(asc(user.email))
      // One more than asked for: whether it came back tells us there is another
      // page without a second count(*).
      .limit(query.limit + 1);

    const hasMore = rows.length > query.limit;
    const page = hasMore ? rows.slice(0, query.limit) : rows;
    const last = page.at(-1);

    const body: ListUsersResponse = {
      data: page.map((row) => ({
        id: row.id,
        name: row.name,
        email: row.email,
        // `role` is nullable only because the Better Auth generator made it so;
        // the column defaults to 'agent'. userSummarySchema requires it, so an
        // unguarded NULL would throw inside the SPA's response parse — three
        // layers away from this line.
        role: row.role ?? "agent",
        createdAt: row.createdAt.toISOString(),
      })),
      nextCursor: hasMore && last ? encodeCursor(last.email) : null,
    };

    res.json(body);
  });

  /**
   * The only way to create a staff account over HTTP. Sign-up is closed (see
   * auth.ts), so this route and `seed.ts` are the two doors, and this one is
   * admin-gated.
   */
  router.post("/users", requireRole("admin"), async (req, res) => {
    // Validation first, as in GET above: a malformed body should get a 400 that
    // describes it rather than a 503 that blames the database. Throws ZodError,
    // which Express 5 routes to the error handler as `validation_failed`.
    const input = createUserBodySchema.parse(req.body);

    // The email is the only field safe to log — the password must never reach a
    // log line, and a request id already ties this to the rest of the request.
    req.log.debug({ email: input.email }, "creating user");

    if (!db) throw HttpError.serviceUnavailable("Database unavailable");
    // Not reachable in practice: with no auth instance `requireAuth` answers 401
    // to everything, so nothing gets this far. Narrowing the type honestly beats
    // asserting past it, and the failure mode matches the missing database.
    if (!auth) throw HttpError.serviceUnavailable("Authentication unavailable");

    const created = await createStaffAccount(auth, input);

    // autoSignIn is on (deliberately — see createStaffAccount), so sign-up also
    // wrote a session row for an account nobody has signed into. Its token was
    // never returned to anyone, which makes it an unusable credential with a
    // multi-day lifetime; deleting it keeps "a session row means someone is
    // signed in" true, which is the property the whole no-cookieCache design
    // exists to preserve.
    await db.delete(session).where(eq(session.userId, created.user.id));

    const body: CreateUserResponse = {
      id: created.user.id,
      name: created.user.name,
      email: created.user.email,
      // Same guard as the projection in GET: `role` is nullable in the generated
      // auth schema even though the column defaults to 'agent'.
      role: created.user.role ?? "agent",
      createdAt: created.user.createdAt.toISOString(),
    };

    res.status(201).json(body);
  });

  /**
   * Edit a staff account: name, email, and optionally the password.
   *
   * PATCH rather than PUT because the password really is optional — a body
   * carrying only a name and email means "leave the password alone", which is a
   * partial update rather than a replacement with a field left out.
   */
  router.patch("/users/:id", requireRole("admin"), async (req, res) => {
    // A path param is untrusted input like any other. A non-UUID cannot name a
    // row, so this could 404, but 400 tells the caller what is actually wrong —
    // the same call `decodeCursor` makes about a malformed cursor above.
    const id = userSchema.shape.id.safeParse(req.params.id);
    if (!id.success) throw HttpError.badRequest("Malformed user id");

    // Validation before the database check, as in the routes above. By the time
    // this returns, a blank or whitespace-only password has already become
    // `undefined` (see updateUserBodySchema), so "leave it alone" is one case.
    const input = updateUserBodySchema.parse(req.body);

    // Whether the password changed is worth a log line; the password is not.
    req.log.debug(
      { userId: id.data, passwordChanged: input.password !== undefined },
      "updating user",
    );

    if (!db) throw HttpError.serviceUnavailable("Database unavailable");
    if (!auth) throw HttpError.serviceUnavailable("Authentication unavailable");

    // The two writes below cannot share a transaction: Better Auth's adapter
    // holds its own handle, so `setStaffPassword` runs outside anything opened
    // here. The order is therefore chosen for its failure mode. This way a
    // password that fails to write leaves the name and email changed and the
    // old password working, and re-submitting the same form converges. The
    // reverse order fails far worse: a duplicate-email 409 after the password
    // had already been replaced would tell the admin nothing happened, while
    // the account's password had in fact changed and its sessions were gone.
    //
    // `name` and `email` are plain columns and are written with Drizzle, the
    // way this file already reads them. Nothing caches a user row — auth.ts
    // sets no cookieCache and no secondaryStorage — so no Better-Auth-side
    // state goes stale behind a direct UPDATE.
    let updated;
    try {
      updated = await db
        .update(user)
        .set({ name: input.name, email: input.email })
        .where(eq(user.id, id.data))
        .returning({
          id: user.id,
          name: user.name,
          email: user.email,
          role: user.role,
          createdAt: user.createdAt,
        });
    } catch (error) {
      if (!isDuplicateEmail(error)) throw error;
      throw HttpError.conflict("A user with that email already exists.");
    }

    // Zero rows updated means no such user, so the UPDATE doubles as the
    // existence check and there is no SELECT-then-write race to lose.
    const row = updated[0];
    if (!row) throw HttpError.notFound("User not found");

    if (input.password !== undefined) {
      await setStaffPassword(auth, row.id, input.password);

      // A password change has to end the sessions it was meant to shut out, or
      // an admin resetting a compromised account leaves the intruder signed in
      // behind a multi-day cookie. Deleting the rows is enough precisely
      // because auth.ts sets no cookieCache: every request re-reads this table,
      // so the next one fails. It applies to the admin's own sessions too when
      // they change their own password, which is the same bargain every other
      // console makes.
      await db.delete(session).where(eq(session.userId, row.id));
    }

    const body: UpdateUserResponse = {
      id: row.id,
      name: row.name,
      email: row.email,
      // Same guard as the routes above: `role` is nullable in the generated
      // auth schema even though the column defaults to 'agent'.
      role: row.role ?? "agent",
      createdAt: row.createdAt.toISOString(),
    };

    res.json(body);
  });

  return router;
}
